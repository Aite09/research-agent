"""
graph/state.py

Defines the shared AgentState TypedDict that flows through every node
in the LangGraph StateGraph. All agents read from and write to this schema.

Why TypedDict?
  LangGraph requires a typed schema for its state. TypedDict gives us
  full type-checking with zero runtime overhead — it's just a dict at runtime.
"""

from typing import List, TypedDict


class SearchResult(TypedDict):
    """A single web search result from Tavily, truncated for LLM consumption."""

    query: str    # The sub-query that produced this result
    url: str      # Source URL
    title: str    # Page title
    content: str  # Page content, truncated to 1500 chars max


class AgentState(TypedDict):
    """
    Shared state passed between all agents in the research pipeline.

    Flow:
        START → planner → search → writer → critic → END
                                               ↑         |
                                               └─────────┘
                                     (loops back if quality_score < 7, max 2 times)
    """

    query: str                        # Original user research question
    search_queries: List[str]         # Sub-queries generated by Planner (3–5)
    search_results: List[SearchResult] # Raw search results collected by Search agent
    report: str                       # Markdown report generated by Writer agent
    quality_score: float              # Score 1–10 assigned by Critic agent
    critique: str                     # Critic's written feedback for Writer revision
    revision_count: int               # How many revision loops have occurred (max 2)
    messages: List[dict]              # Full conversation log, auto-appended by agents
    status: str                       # Pipeline status: "planning"|"searching"|"writing"|"critiquing"|"done"|"error"
    error: str                        # Error message if any agent fails, else empty string
